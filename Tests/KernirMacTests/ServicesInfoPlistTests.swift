import Testing
import Foundation
@testable import Kernir

/// Finder Services (02a steps 5, 6): the `NSServices` entries in App/macOS/Info.plist. The file is
/// read from the repository (through a symlinked copy of this file too), so this runs without a
/// built app; `hostedAppCarriesTheSameServices` checks the built bundle when hosted in Lutik.app.
struct ServicesInfoPlistTests {
    private static let infoPlist = URL(fileURLWithPath: #filePath).resolvingSymlinksInPath()
        .deletingLastPathComponent().deletingLastPathComponent().deletingLastPathComponent()
        .appendingPathComponent("App/macOS/Info.plist")

    private static func services() throws -> [[String: Any]] {
        let data = try Data(contentsOf: infoPlist)
        let plist = try #require(
            try PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any])
        return try #require(plist["NSServices"] as? [[String: Any]])
    }

    private static func service(_ message: String) throws -> [String: Any] {
        try #require(try services().first { $0["NSMessage"] as? String == message }, "no \(message)")
    }

    @Test func exactlyTheTwoServicesTheProviderImplements() throws {
        let messages = try Self.services().compactMap { $0["NSMessage"] as? String }
        #expect(messages.count == 2)
        #expect(Set(messages) == Set(ServicesProvider.messages))
    }

    /// AppKit delivers each NSMessage as `<message>:userData:error:` to `NSApp.servicesProvider`:
    /// the provider class has that `@objc` method for every entry, so no Service is a dead item.
    @Test func everyMessageHasItsProviderMethod() throws {
        let messages = try Self.services().map { try #require($0["NSMessage"] as? String) }
        #expect(!messages.isEmpty)
        for message in messages {
            #expect(ServicesProvider.instancesRespond(to: NSSelectorFromString(message + ":userData:error:")),
                    "ServicesProvider has no \(message):userData:error:")
        }
    }

    @Test func extractHereSendsEveryArchiveType() throws {
        let types = try #require(try Self.service("extractHere")["NSSendFileTypes"] as? [String])
        #expect(types.count == Set(types).count)
        #expect(Set(types) == Set(KernirDocumentTypes.identifiers + ["com.sun.java-archive", "org.python.wheel"]))
        // Of the zip-based packages (a viewer only otherwise), Extract Here offers .jar and .whl
        // only.
        for type in KernirDocumentTypes.packageTypes where !["com.sun.java-archive", "org.python.wheel"].contains(type.identifier) {
            #expect(!types.contains(type.identifier))
        }
    }

    @Test func compressSendsAnyItem() throws {
        #expect(try Self.service("compress")["NSSendFileTypes"] as? [String] == ["public.item"])
    }

    @Test(arguments: [("extractHere", "Extract Here with Lutik"), ("compress", "Compress with Lutik")])
    func menuTitlePortAndContext(message: String, title: String) throws {
        let entry = try Self.service(message)
        #expect((entry["NSMenuItem"] as? [String: String])?["default"] == title)
        #expect(entry["NSPortName"] as? String == "Lutik")
        let context = try #require(entry["NSRequiredContext"] as? [String: Any])
        #expect(context.isEmpty)
        // No pasteboard types: these services take files only and return nothing.
        #expect(entry["NSSendTypes"] == nil)
        #expect(entry["NSReturnTypes"] == nil)
    }

    /// Hosted in Lutik.app (TEST_HOST), Bundle.main is the app: the built Info.plist carries the
    /// same entries as the repository file. Skipped when not hosted (the scratch SwiftPM run).
    @Test(.enabled(if: Bundle.main.bundleIdentifier?.hasPrefix("com.kernir.app") == true))
    func hostedAppCarriesTheSameServices() throws {
        let built = try #require(Bundle.main.infoDictionary?["NSServices"] as? NSArray)
        #expect(built.isEqual(try Self.services() as NSArray))
    }

    private static func menuTitles() throws -> Set<String> {
        Set(try services().map { try #require(($0["NSMenuItem"] as? [String: String])?["default"]) })
    }

    /// AppKit localizes a Service's menu title through the bundle's ServicesMenu.strings,
    /// keyed by its NSMenuItem default. App/macOS/ServicesMenu.xcstrings (generated by
    /// scripts/l10n/infoplist_catalogs.py) has exactly those keys.
    @Test func servicesMenuCatalogHasEveryMenuTitle() throws {
        let url = Self.infoPlist.deletingLastPathComponent().appendingPathComponent("ServicesMenu.xcstrings")
        let catalog = try #require(
            try JSONSerialization.jsonObject(with: Data(contentsOf: url)) as? [String: Any])
        let strings = try #require(catalog["strings"] as? [String: Any])
        #expect(Set(strings.keys) == (try Self.menuTitles()))
    }

    /// Hosted: the build compiled that catalog into the app's ServicesMenu table.
    @Test(.enabled(if: Bundle.main.bundleIdentifier?.hasPrefix("com.kernir.app") == true))
    func hostedAppHasTheServicesMenuTable() throws {
        #expect(Bundle.main.path(forResource: "ServicesMenu", ofType: "strings") != nil)
        for title in try Self.menuTitles() {
            #expect(Bundle.main.localizedString(forKey: title, value: "(missing)", table: "ServicesMenu") == title)
        }
    }
}
