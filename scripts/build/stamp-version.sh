#!/bin/bash
# Stamps the build: writes App/Version.generated.xcconfig (gitignored), which App/Version.xcconfig
# (the project-level config of every target, project.yml configFiles) includes:
#   CURRENT_PROJECT_VERSION = <commit count of HEAD>   -> CFBundleVersion of the apps and extensions
#   KERNIR_GIT_COMMIT = <short SHA of HEAD>             -> KernirGitCommit in the apps' Info.plist (About)
# xcodegen runs it before every generate (project.yml options.preGenCommand), so a build is stamped with
# the commit the project was generated at. Release scripts still pass CURRENT_PROJECT_VERSION on the
# xcodebuild command line (scripts/lib/common.sh build_number, BUILD_NUMBER override), which wins.
# Fallbacks (a warning on stderr, exit 0, so xcodegen still runs):
#   shallow clone -> SHA only: its commit count is wrong, so the committed default build number 1 applies;
#   not a git checkout (source archive) -> no generated file: the defaults (1, dev) apply.
# Usage: scripts/build/stamp-version.sh   (from any directory; the repo is the one holding this script)
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
out="$root/App/Version.generated.xcconfig"
warn() { echo "stamp-version: warning: $*" >&2; }

if ! sha="$(git -C "$root" rev-parse --short=7 HEAD 2>/dev/null)"; then
  warn "$root is not a git checkout: build number 1, commit dev (App/Version.xcconfig defaults)"
  rm -f "$out"
  exit 0
fi

text="// Generated by scripts/build/stamp-version.sh at xcodegen time; do not edit or commit."$'\n'
if [ "$(git -C "$root" rev-parse --is-shallow-repository)" = true ]; then
  warn "$root is a shallow clone, its commit count is wrong: build number 1 (fetch with --unshallow to stamp it)"
else
  text+="CURRENT_PROJECT_VERSION = $(git -C "$root" rev-list --count HEAD)"$'\n'
fi
text+="KERNIR_GIT_COMMIT = $sha"$'\n'

# Rewritten only on change, atomically (a build reading it never sees half a file).
if [ "$(cat "$out" 2>/dev/null)"$'\n' != "$text" ]; then
  printf '%s' "$text" > "$out.tmp.$$"
  mv -f "$out.tmp.$$" "$out"
fi
echo "stamp-version: $(sed -n 's/^CURRENT_PROJECT_VERSION = //p' "$out" | grep . || echo 1) ($sha)" >&2
